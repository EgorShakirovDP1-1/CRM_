export function useI18n() {
    const page = usePage();
    const locale = computed<'ru' | 'en'>(() =>
        page.props.locale === 'ru' ? 'ru' : 'en',
    );
    const t = (key: keyof typeof messages.en): string =>
        messages[locale.value][key];

    return { locale, t };
}
